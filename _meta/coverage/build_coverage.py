#!/usr/bin/env python3
"""Generate the raw-layer coverage block of CLAUDE.md from the files themselves.

Why this exists. The coverage description was written by hand three times and was
wrong within the hour each time, because more than one agent writes to this folder
and only one of them updated the description. Anything mechanically checkable is
therefore generated, never typed. Judgement stays in the hand-written sections of
CLAUDE.md; this script only reports what the files actually say.

Run:  python3 _meta/coverage/build_coverage.py            (writes CLAUDE.md)
      python3 _meta/coverage/build_coverage.py --check    (exit 1 if out of date)
      python3 _meta/coverage/build_coverage.py --stdout   (print, write nothing)
"""

import datetime as dt
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLAUDE = os.path.join(ROOT, "CLAUDE.md")
BEGIN = "<!-- COVERAGE:BEGIN - generated by _meta/coverage/build_coverage.py, do not edit by hand -->"
END = "<!-- COVERAGE:END -->"

STALE_YEARS = 2
SKIP_PREFIX = ("_", "md-", "README")
EU_PREFIX = "UE-"
TREATY_PREFIX = "AA-"  # Acordul de Asociere, extrase (2026-09-15, pasul 6.3)

ANCHOR_RE = re.compile(r"^## Articolul\s+(\d+)(?:\^(\d+))?", re.M)
# Forma veche "Art.N. -", gasita 2026-09-16 la L-1125-2002 (republicata 2019, dar nenormalizata
# de legis.md la "Articolul N."). Ancora pastreaza textul original al liniei ("## Art.N. - ..."),
# deci ANCHOR_RE de mai sus nu o vede: fara aceasta a doua regula, coverage arata "declared N,
# found 0" pentru orice act ancorat prin aceasta forma. Aceleasi doua grupuri (numar, exponent),
# ca findall() sa produca tupluri compatibile cu ANCHOR_RE mai sus.
ANCHOR_ABBR_RE = re.compile(r"^## Art\.\s*(\d+)(?:\^(\d+))?\.\s*[-–—]", re.M)
# English-form anchors written by anchor_bnm_en.py on 2026-09-04; forbidden on translations (D2).
ANCHOR_EN_RE = re.compile(r"^## Article\s+\d", re.M)
# 2026-09-06: punctul dupa numeral nu este obligatoriu. CONST-1994 scrie `## Articolul I` fara
# punct (titlul sta pe linia urmatoare), iar forma veche numara 149 in loc de 157 si raporta o
# nepotrivire falsa. Aceeasi corectie ca in verify_business_law.py la 2026-09-05.
ROMAN_RE = re.compile(r"^## Articolul\s+([IVXLC]+)(?=[.\s]|$)", re.M)
DECL_RE = re.compile(r"\*\*articole detectate:\*\*\s*(\d+)")
POINTS_RE = re.compile(r"\*\*puncte numerotate detectate:\*\*\s*(\d+)")
BODY_ART_RO = re.compile(r"^Articolul\s+\d", re.M)
BODY_ART_ABBR = re.compile(r"^Art\.\s*\d+\.\s*[-\u2013\u2014]", re.M)
BODY_ART_EN = re.compile(r"^Article\s+\d", re.M)


def read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def frontmatter(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    fm = {}
    key = None
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", line)
        if m:
            key = m.group(1)
            fm[key] = m.group(2).strip().strip("'\"")
        elif line.startswith("- ") and key:
            fm.setdefault(key + "__list", []).append(line[2:].strip().strip("'\""))
    return fm


def flattened_superscripts(nums):
    """A heading number that extends its predecessor's digits is a flattened
    superscript: 146 followed by 1461 is article 146^1, not article 1461."""
    out = []
    for a, b in zip(nums, nums[1:]):
        sa, sb = str(a), str(b)
        if len(sb) > len(sa) and sb.startswith(sa):
            out.append(f"{sa}^{sb[len(sa):]} stored as {sb}")
    return out


def is_future_consolidation(consolidation_date, today):
    """Consolidarea leaga azi sau nu, calculat mereu din data, niciodata din steagul inghetat.

    Gasit 2026-09-19: fm['consolidation_is_future'] e scris o singura data, la ingerare
    (ingest_business_law.py), si ramine asa pentru totdeauna -- daca data trece intre timp,
    steagul nu se actualizeaza singur. COD-218-2008 si L-158-2008 (consolidare 2026-09-13)
    au ramas marcate "in viitor" desi data e azi trecuta. Registrul in-force deja calcula
    live (`cd > as_of`); tabelul de acoperire il urmeaza acum, ca sa nu mai difere intre ele.
    """
    if not consolidation_date:
        return False
    try:
        return dt.date.fromisoformat(consolidation_date) > today
    except ValueError:
        return False


def stale_age_note(consolidation, today):
    """Return the stable stale-source marker, if a consolidation is stale."""
    try:
        age = (today - dt.date.fromisoformat(consolidation)).days / 365.25
    except ValueError:
        return None
    return "**more than 2 years old**" if age > STALE_YEARS else None


def scan_file(path, rel, today):
    text = read(path)
    fm = frontmatter(text)
    body = text.split("\n---", 1)[-1] if text.startswith("---") else text
    anchors = ANCHOR_RE.findall(text) + ANCHOR_ABBR_RE.findall(text)
    roman = ROMAN_RE.findall(text)
    plain = [int(a) for a, s in anchors if not s]
    sup = [f"{a}^{s}" for a, s in anchors if s]
    body_decl = DECL_RE.search(text)
    points = POINTS_RE.search(text)
    fm_decl = fm.get("articole detectate")
    if fm_decl is None:
        m = re.search(r"^articole detectate:\s*(\d+)", text[:4000], re.M)
        fm_decl = m.group(1) if m else None
    return {
        "rel": rel,
        "id": fm.get("instrument_id") or os.path.basename(path)[:-3],
        "consolidation": fm.get("consolidation_date", ""),
        "future": is_future_consolidation(fm.get("consolidation_date", ""), today),
        "refreshed": fm.get("refreshed", ""),
        "full_text": fm.get("full_text", "").lower() == "true",
        "declared": int(fm_decl) if fm_decl is not None else (int(body_decl.group(1)) if body_decl else None),
        "body_declared": int(body_decl.group(1)) if body_decl else None,
        "points": int(points.group(1)) if points else None,
        "anchors": len(anchors) + len(roman),
        "roman": len(roman),
        "never_amended": fm.get("latest_modification_line", "").startswith("Publicat"),
        # Abrogarea, din 2026-09-10. Un act abrogat are o consolidare recenta si trecuta, deci
        # trecea drept `clean` aici: singurul semn ca incetase sa lege statea in corpul textului.
        # Scris de repeal_of() in ingest_business_law.py.
        "repealed": fm.get("repealed", "").lower() == "true",
        "repeal_effective": fm.get("repeal_effective", ""),
        "repealed_by": fm.get("repealed_by", ""),
        "repeal_in_force_today": fm.get("repeal_in_force_today", "").lower() == "true",
        "plain": plain,
        "superscript_anchors": sup,
        "superscript_declared": fm.get("superscript_articles__list", []),
        "pre_anchoring": "sha256_pre_anchoring" in fm,
        "body_ro": len(BODY_ART_RO.findall(body)),
        "body_abbr": len(BODY_ART_ABBR.findall(body)),
        "body_en": len(BODY_ART_EN.findall(body)),
        "flattened": flattened_superscripts(sorted(set(plain))),
    }


def collect(today):
    acts, eu, treaty, bnm_unanchored, other = [], 0, 0, [], 0
    bnm_en_anchored = []
    # bnm/legal-ro holds the six banking laws in Romanian (P8, 2026-09-05): primary acts,
    # counted with cnpf and moldova-legal, and kept out of the BNM English walk below.
    for folder in ("cnpf", "moldova-legal", "bnm/legal-ro"):
        d = os.path.join(ROOT, "raw", "papers", folder)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not name.endswith(".md") or name.startswith(SKIP_PREFIX):
                continue
            if name.startswith(EU_PREFIX):
                eu += 1
                continue
            if name.startswith(TREATY_PREFIX):
                # AA-2014 (2026-09-15, pasul 6.3): extras al Acordului de Asociere, nu un act
                # moldovenesc -- numarat separat, ca extrasele UE, nu in tabelul actelor primare.
                treaty += 1
                continue
            acts.append(scan_file(os.path.join(d, name), f"raw/papers/{folder}/{name}", today))
    bnm = os.path.join(ROOT, "raw", "papers", "bnm")
    for dirpath, _dirs, files in os.walk(bnm):
        if os.path.basename(dirpath) == "legal-ro":
            continue
        for name in files:
            if not name.endswith(".md"):
                continue
            other += 1
            text = read(os.path.join(dirpath, name))
            if ANCHOR_RE.search(text):
                continue
            if ANCHOR_EN_RE.search(text):
                bnm_en_anchored.append(name)
                continue
            n = len(BODY_ART_EN.findall(text))
            if n:
                bnm_unanchored.append(n)
    collect.bnm_en_anchored = bnm_en_anchored
    return acts, eu, treaty, bnm_unanchored, other


def inforce():
    p = os.path.join(ROOT, "_meta", "inforce", "in-force-register.json")
    if not os.path.exists(p):
        return None
    try:
        return json.loads(read(p))
    except Exception:
        return None


def hcc():
    """Registrul HCC (_meta/hcc/), al patrulea control generat, 2026-09-15 (D4 i).

    De ce contează pentru bloc: o dispoziție declarată neconstituțională arată identic cu
    oricare alta -- articolul există, ancora e valida, sha256 se potriveste. Simetricul
    "Not yet in force": acolo textul viitor nu leagă azi, aici textul de azi nu mai leagă,
    pentru ca a fost anulat, dar consolidarea detinuta nu o spune la nivel de articol decat
    daca marcajul a supravietuit sau a fost recuperat in recovered-provisions.json.
    """
    p = os.path.join(ROOT, "_meta", "hcc", "hcc-register.json")
    if not os.path.exists(p):
        return None
    try:
        return json.loads(read(p))
    except Exception:
        return None


def build(today):
    acts, eu, treaty, bnm_unanchored, bnm_total = collect(today)
    reg = inforce()
    hcc_reg = hcc()
    hcc_by_act = {}
    if hcc_reg:
        for x in hcc_reg["acts"]:
            known = len(x["distinct_hcc"]) - len(x["unattributed"])
            hcc_by_act[x["instrument"]] = {
                "known": known,
                "unattributed": len(x["unattributed"]),
            }
    L = []
    a = L.append

    a(BEGIN)
    a("")
    a("## State of the raw layer")
    a("")
    a(f"Generated {dt.datetime.now().strftime('%Y-%m-%d %H:%M')} from the files themselves. "
      "Do not edit this section by hand; rerun `python3 _meta/coverage/build_coverage.py`. "
      "Judgement belongs in the hand-written sections above and below.")
    a("")
    a(f"{len(acts)} primary Moldovan acts, {eu} EU acquis extracts, {treaty} Association Agreement "
      f"extract(s), {bnm_total} BNM corpus documents.")
    a("")
    a("| Act | Articles | Anchors | Consolidation | Note |")
    a("|---|---:|---:|---|---|")
    for x in sorted(acts, key=lambda r: r["id"]):
        notes = []
        # Abrogarea se scrie prima: orice altceva despre un act mort este secundar.
        if x["repealed"]:
            notes.append(f"**ABROGAT de la {x['repeal_effective']}**"
                         if x["repeal_in_force_today"] else
                         f"**abrogare cu efect de la {x['repeal_effective']}**")
        if x["declared"] is not None and x["declared"] != x["anchors"]:
            notes.append(f"**declared {x['declared']}, found {x['anchors']}**")
        if x["roman"]:
            notes.append(f"{x['roman']} articles numbered in Roman figures")
        if x["anchors"] == 0:
            if x["points"]:
                notes.append(f"numbered points ({x['points']}), not articles")
            elif x["body_ro"] or x["body_abbr"]:
                notes.append(f"**{x['body_ro'] + x['body_abbr']} article markers in body, none anchored**")
            else:
                notes.append("no article structure")
        if x["future"]:
            notes.append("**consolidation dated in the future**")
        elif x["consolidation"] and not x["never_amended"]:
            age_note = stale_age_note(x["consolidation"], today)
            if age_note:
                notes.append(age_note)
        if x["flattened"]:
            notes.append("**suspected flattened superscript: " + "; ".join(x["flattened"]) + "**")
        if x["superscript_anchors"]:
            n = len(x["superscript_anchors"])
            notes.append(f"{n} superscript article{'s' if n > 1 else ''} normalised")
        if x["body_declared"] is not None and x["body_declared"] != x["anchors"]:
            notes.append(f"stale count line in body says {x['body_declared']}")
        hx = hcc_by_act.get(x["id"])
        if hx:
            if hx["unattributed"]:
                notes.append(f"**{hx['unattributed']} HCC decision(s) not yet attributed to an article**"
                             + (f" ({hx['known']} known)" if hx["known"] else ""))
            else:
                notes.append(f"{hx['known']} provision(s) declared unconstitutional (HCC register)")
        a(f"| `{x['id']}` | {x['declared'] if x['declared'] is not None else '-'} "
          f"| {x['anchors']} | {x['consolidation'] or '-'} | {'; '.join(notes) or 'clean'} |")
    a("")

    flags = []
    rep = [x for x in acts if x["repealed"]]
    if rep:
        gone = [x for x in rep if x["repeal_in_force_today"]]
        soon = [x for x in rep if not x["repeal_in_force_today"]]
        parts = []
        if gone:
            parts.append("no longer in force: "
                         + ", ".join(f"`{x['id']}` (repealed {x['repeal_effective']}"
                                     + (f" by {x['repealed_by']}" if x["repealed_by"] else "") + ")"
                                     for x in sorted(gone, key=lambda r: r["repeal_effective"])))
        if soon:
            parts.append("repeal already enacted but not yet effective: "
                         + ", ".join(f"`{x['id']}` (from {x['repeal_effective']})" for x in soon))
        flags.append(
            "**Repealed acts.** " + "; ".join(parts)
            + ". These files are kept because other acts in the corpus still cite them and "
              "because the text governs facts before the repeal date. They are anchored, their "
              "sha256 verifies and their consolidation is recent, so nothing else here would "
              "reveal that they stopped binding. Do not cite them as law in force; cite the "
              "successor and say from when it applies.")
    fut = [x for x in acts if x["future"]]
    if fut:
        n = len(reg["provisions_not_yet_in_force"]) if reg else "?"
        flags.append(
            f"**Not yet in force.** {len(fut)} act(s) carry a consolidation dated after today, so the file "
            f"holds text that will bind later, not text that binds now: "
            + ", ".join(f"`{x['id']}` ({x['consolidation']})" for x in fut)
            + f". {n} affected provision(s) are listed in `_meta/inforce/in-force-register.md`. "
            "Check that register before citing an article from these acts. The citation will look "
            "correct in every other respect: the article exists, the anchor is valid, the sha256 matches.")
    if hcc_reg:
        c = hcc_reg["counts"]
        struck_acts = [aid for aid, hx in hcc_by_act.items() if hx["known"]]
        flags.append(
            f"**Declared unconstitutional.** {c['acts']} act(s) carry at least one Constitutional Court "
            f"decision in their history block, {c['distinct_hcc']} decisions in total: {c['markers_in_text']} "
            f"still marked at article level in the text itself, {c['recovered']} more recovered by reading "
            f"the legis.md version history (`_meta/hcc/recovered-provisions.json`), and "
            f"{c['unattributed']} not yet attributed to any article. A struck provision looks like ordinary "
            "law: the article exists, the anchor is valid, the sha256 matches. Check "
            "`_meta/hcc/hcc-register.md` before citing an article from "
            + ", ".join(f"`{aid}`" for aid in sorted(struck_acts))
            + " and say which decision struck it and what today's text actually holds.")
    stale = []
    for x in acts:
        if x["future"] or not x["consolidation"] or x["never_amended"]:
            continue
        if stale_age_note(x["consolidation"], today):
            stale.append(x)
    if stale:
        flags.append("**Stale consolidations.** "
                     + ", ".join(f"`{x['id']}` ({x['consolidation']})" for x in sorted(stale, key=lambda r: r["consolidation"]))
                     + ". Anchoring is clean, so these look reliable. Say in the answer that the text may be superseded.")
    flat = [x for x in acts if x["flattened"]]
    if flat:
        flags.append("**Suspected flattened superscripts still present.** "
                     + "; ".join(f"`{x['id']}`: " + ", ".join(x["flattened"]) for x in flat))
    body_stale = [x for x in acts if x["body_declared"] is not None and x["body_declared"] != x["anchors"]]
    if body_stale:
        flags.append("**Stale count line inside the file.** "
                     + ", ".join(f"`{x['id']}` (body says {x['body_declared']}, anchors {x['anchors']})" for x in body_stale)
                     + ". The frontmatter is right and the anchors are right; the human-readable line in the "
                       "body was written by the original ingest and never updated. Cosmetic, but it is the "
                       "line a reader sees first.")
    mismatch = [x for x in acts if x["declared"] is not None and x["declared"] != x["anchors"]]
    if mismatch:
        flags.append("**Declared count does not match anchors.** "
                     + ", ".join(f"`{x['id']}` ({x['declared']} vs {x['anchors']})" for x in mismatch))
    unanchored = [x for x in acts if x["anchors"] == 0 and not x["points"] and (x["body_ro"] or x["body_abbr"])]
    if unanchored:
        flags.append("**Full text present but unanchored.** "
                     + ", ".join(f"`{x['id']}`" for x in unanchored)
                     + ". Not citable to article level.")
    if getattr(collect, "bnm_en_anchored", None):
        flags.append(f"**Anchored translations.** {len(collect.bnm_en_anchored)} BNM English file(s) still carry "
                     "`## Article N.` anchors. Decision D2 forbids anchors on a translation; de-anchor them "
                     "or ingest the Romanian text.")
    if bnm_unanchored:
        flags.append(f"**BNM English corpus.** {len(bnm_unanchored)} file(s) carry {sum(bnm_unanchored)} "
                     "line-initial `Article N` markers and no anchors. Any answer resting on the English "
                     "BNM translations is not anchored.")

    a("### Mechanical flags")
    a("")
    if flags:
        for f in flags:
            a(f"- {f}")
    else:
        a("- None. Every act is anchored, every declared count matches, no consolidation is stale or future-dated.")
    a("")
    a(END)
    return "\n".join(L)


def main():
    today = dt.date.today()
    block = build(today)
    if "--stdout" in sys.argv:
        print(block)
        return 0
    text = read(CLAUDE)
    if BEGIN not in text or END not in text:
        sys.stderr.write(f"markers not found in {CLAUDE}; add {BEGIN} and {END}\n")
        return 2
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    new = head + block + tail
    if "--check" in sys.argv:
        cur = BEGIN + _old + END
        same = re.sub(r"Generated \d{4}-\d\d-\d\d \d\d:\d\d", "", cur) == \
               re.sub(r"Generated \d{4}-\d\d-\d\d \d\d:\d\d", "", block)
        print("up to date" if same else "OUT OF DATE")
        return 0 if same else 1
    with open(CLAUDE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print(f"CLAUDE.md coverage block regenerated, {len(block)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
